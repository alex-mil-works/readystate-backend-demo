import { writeFile } from 'node:fs/promises';
import path from 'node:path';

import type { DisciplineManifest } from '../../src/content/schemas/discipline.js';
import { paths } from './paths.js';

export type CatalogRole = {
  id: string;
  label: string;
  stacks: Array<{ id: string; label: string; available: boolean }>;
};

export function manifestsToCatalogRoles(manifests: DisciplineManifest[]): CatalogRole[] {
  return manifests.map((manifest) => ({
    id: manifest.roleId,
    label: manifest.title,
    stacks: manifest.stacks.map((stack) => ({
      id: stack.id,
      label: stack.label,
      available: stack.available === true,
    })),
  }));
}

export function formatDisciplineCatalogTs(roles: CatalogRole[]): string {
  return `/** Generated by yarn content:compile (backend) from .courses/<role>/discipline.yaml. Do not edit. */

export const GENERATED_DISCIPLINE_ROLES = ${JSON.stringify(roles, null, 2)} as const;
`;
}

/** Write catalog snapshot (JSON for API + optional TS for tooling). */
export async function writeDisciplineCatalog(manifests: DisciplineManifest[]): Promise<string> {
  const roles = manifestsToCatalogRoles(manifests);
  const jsonPath = path.join(paths.generatedDir, 'disciplines.json');
  await writeFile(jsonPath, `${JSON.stringify(roles, null, 2)}\n`, 'utf8');

  const tsPath = path.join(paths.generatedDir, 'disciplines.ts');
  await writeFile(tsPath, formatDisciplineCatalogTs(roles), 'utf8');
  return jsonPath;
}
